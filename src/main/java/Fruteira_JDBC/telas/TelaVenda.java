    private void carregarClientes() {

        String sql = "SELECT id, nome FROM clientes";

        try (Connection conexao = Conexao.conectar();
             PreparedStatement pstmt = conexao.prepareStatement(sql);
             ResultSet rs = pstmt.executeQuery()) {

            SelectCliente.removeAllItems();
            SelectCliente.addItem("Selecione um cliente");

            while (rs.next()) {
                SelectCliente.addItem(
                    rs.getInt("id") + " - " + rs.getString("nome")
                );
            }

        } catch (SQLException e) {
            System.out.println("Erro ao carregar clientes.");
            e.printStackTrace();
        }
        
    }
    
    private void carregarProdutos() {

        String sql = "SELECT id, nome, preco FROM produtos";

        try (Connection conexao = Conexao.conectar();
             PreparedStatement pstmt = conexao.prepareStatement(sql);
             ResultSet rs = pstmt.executeQuery()) {

            SelectProduto.removeAllItems();
            SelectProduto.addItem("Selecione um produto");

            while (rs.next()) {
                SelectProduto.addItem(
                    rs.getInt("id") + " - " + rs.getString("nome") + " - R$ " + rs.getDouble("preco")
                );
            }

        } catch (SQLException e) {
            System.out.println("Erro ao carregar produtos.");
            e.printStackTrace();
        }
        
    }
    
    private void calcularTotal() {
        
        if (SelectProduto.getSelectedIndex() == 0 || SelectProduto.getSelectedItem() == null) {
            LblTotal.setText("Total: R$ 0,00");
            return;
        }
        
        try {
            String produtoSelecionado = SelectProduto.getSelectedItem().toString();

            String[] partes = produtoSelecionado.split(" - ");

            double preco = Double.parseDouble(
                partes[2].replace("R$ ", "").replace(",", ".")
            );

            int quantidade = Integer.parseInt(TxtQuantidade.getText());

            double total = preco * quantidade;

            LblTotal.setText(String.format("Total: R$ %.2f", total).replace(".", ","));

        } catch (NumberFormatException e) {
            LblTotal.setText("Total: R$ 0,00");
        }
    }
    
    private void carregarVendas() {

        DefaultTableModel modelo =
            (DefaultTableModel) TblVendas.getModel();

        modelo.setRowCount(0);

        VendaDAO dao = new VendaDAOJdbc();
        List<Object[]> vendas = dao.listarTodasDetalhadas();

        for (int i = 0; i < vendas.size(); i++) {
            modelo.addRow(vendas.get(i));
        }
    }
    

