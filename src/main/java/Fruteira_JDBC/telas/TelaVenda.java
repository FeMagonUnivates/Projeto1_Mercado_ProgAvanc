    private void btnDeletarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeletarActionPerformed

        int linha = TblVendas.getSelectedRow();

        if (linha < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma venda na tabela.");
            return;
        }

        int id = Integer.parseInt(TblVendas.getValueAt(linha, 0).toString());

        VendaDAO dao = new VendaDAOJdbc();
        boolean sucesso = dao.excluir(id);

        if (sucesso) {
            DefaultTableModel modelo = (DefaultTableModel) TblVendas.getModel();
            modelo.removeRow(linha);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao excluir venda.");
        }
    }//GEN-LAST:event_btnDeletarActionPerformed

