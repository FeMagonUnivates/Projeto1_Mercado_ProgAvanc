    private void BtnFinalizarVendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnFinalizarVendaActionPerformed
        
        if (SelectCliente.getSelectedIndex() == 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Selecione um cliente."
            );
            return;
        }
        
        if (SelectProduto.getSelectedIndex() == 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Selecione um produto."
            );
            return;
        }
        
        if (TxtQuantidade.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Informe a quantidade."
            );
            return;
        }
        
        int clienteId = Integer.parseInt(
            SelectCliente.getSelectedItem().toString().split(" - ")[0]
        );

        int produtoId = Integer.parseInt(
            SelectProduto.getSelectedItem().toString().split(" - ")[0]
        );

        int quantidadeProduto = Integer.parseInt(TxtQuantidade.getText());
        
        Venda venda = new Venda();
        venda.setClienteId(clienteId);
        venda.setProdutoId(produtoId);
        venda.setQuantidade(quantidadeProduto);
        
        VendaDAO dao = new VendaDAOJdbc();
        boolean sucesso = dao.cadastrar(venda);
        
        carregarVendas();

        SelectCliente.setSelectedIndex(0);
        SelectProduto.setSelectedIndex(0);
        TxtQuantidade.setText("");
        LblTotal.setText("Total: R$ 0,00");
        
    }//GEN-LAST:event_BtnFinalizarVendaActionPerformed

